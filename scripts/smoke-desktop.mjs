import { dismissOnboarding } from './dismiss-onboarding.mjs';
import { _electron as electron } from '@playwright/test';
import electronBinary from 'electron';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const artifacts = resolve(root, 'artifacts');
await mkdir(artifacts, { recursive: true });
const testDir = resolve(root, '.tmp', `desktop-${Date.now()}`);
const env = { ...process.env, BUSINESSMAP_DATA_DIR: testDir, BUSINESSMAP_HEADLESS: '1', PYTHONUTF8: '1' };
delete env.ELECTRON_RUN_AS_NODE;
const packaged = process.env.BUSINESSMAP_TEST_EXECUTABLE;
const desktop = await electron.launch({ executablePath: packaged || electronBinary, args: packaged ? [] : [root], cwd: root, env, chromiumSandbox: true, timeout: 90_000 });
const errors = [];
try {
  const page = await desktop.firstWindow({ timeout: 90_000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const screenshot = async (filename) => {
    const path = resolve(artifacts, filename);
    await desktop.evaluate(async ({ BrowserWindow }) => { await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined, { stayHidden: true, stayAwake: true }); });
    // Let the 150–180 ms theme transitions settle. Native capture wakes hidden
    // windows reliably; Playwright's screenshot can stall after the fonts load.
    await page.waitForTimeout(250);
    const png = await desktop.evaluate(async ({ BrowserWindow }) => {
      const captured = await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined, { stayHidden: true, stayAwake: true });
      if (captured.isEmpty()) throw new Error('Native desktop capture is empty');
      return captured.toPNG().toString('base64');
    });
    await writeFile(path, Buffer.from(png, 'base64'));
  };
  page.on('pageerror', (error) => errors.push(error.message));
  await dismissOnboarding(page);
  await page.waitForFunction(() => !!window.businessmap, { timeout: 30_000 });
  const api = (method, path, body) => page.evaluate(async ({ method, path, body }) => window.businessmap.request(method, path, body), { method, path, body });
  const workspace = await api('GET', '/api/workspace');
  assert.ok(workspace.stats.notes >= 5, 'demo Vault exists');
  assert.equal(workspace.demo, true);
  const { notes } = await api('GET', '/api/notes');
  const graph = await api('GET', '/api/graph');
  assert.ok(graph.nodes.length >= 5 && graph.edges.length >= 3, 'real linked Markdown graph');
  const note = await api('GET', `/api/note?path=${encodeURIComponent(notes[0].path)}`);
  const update = await api('PUT', '/api/note', { path: note.path, content: `${note.content}\n\n桌面集成测试补充。\n`, revision: note.revision });
  assert.notEqual(update.revision, note.revision);
  let conflict = false;
  try { await api('PUT', '/api/note', { path: note.path, content: '旧版本不应覆盖', revision: note.revision }); } catch { conflict = true; }
  assert.ok(conflict, 'stale saves are rejected');
  await api('PUT', '/api/note', { path: note.path, content: note.content, revision: update.revision });
  const { datasources } = await api('GET', '/api/datasources');
  const source = datasources.find((item) => item.demo) || datasources[0];
  assert.ok(source, 'demo read-only datasource available');
  const result = await api('POST', '/api/query', { datasource_id: source.id, sql: 'SELECT channel, COUNT(*) AS orders, SUM(amount) AS revenue FROM orders GROUP BY channel ORDER BY channel' });
  assert.ok(result.rows.length > 0 && result.columns.length === 3);
  let denied = false;
  try { await api('POST', '/api/query', { datasource_id: source.id, sql: 'DELETE FROM orders' }); } catch { denied = true; }
  assert.ok(denied, 'write SQL rejected');
  const repeat = await api('POST', '/api/query', { datasource_id: source.id, sql: result.sql });
  assert.deepEqual(repeat.rows, result.rows, 'denied write leaves data unchanged');
  const report = await api('POST', '/api/reports', { result_id: result.id, title: '渠道订单分析', chart_type: 'bar' });
  assert.equal(report.result.id, result.id);
  const answer = await api('POST', '/api/chat', { message: '退款规则', mode: 'knowledge' });
  assert.ok(answer.answer && answer.sources.length, 'grounded local support works without a model');
  const settings = await api('GET', '/api/settings');
  assert.equal(settings.active_provider_id, null);
  const navigation = page.getByRole('navigation', { name: '应用导航' });
  assert.deepEqual(await navigation.locator('.navigation-item').allTextContents(), ['模型配置', '项目与仓库', '数据库', 'AI 问答', '业务地图']);
  await page.getByRole('button', { name: '浅色主题', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'light');
  await screenshot('desktop-chat-light.png');
  await navigation.getByRole('button', { name: '业务地图', exact: true }).click();
  await page.getByRole('button', { name: '关系图谱', exact: true }).click();
  await page.waitForTimeout(1400);
  await screenshot('desktop-graph.png');
  await page.getByRole('button', { name: '文档', exact: true }).click();
  await page.waitForTimeout(500);
  await screenshot('desktop-knowledge.png');
  await page.getByRole('button', { name: '深色主题', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'dark');
  await screenshot('desktop-knowledge-dark.png');
  await navigation.getByRole('button', { name: '数据库', exact: true }).click();
  await page.getByLabel('SQL 查询编辑器').fill('SELECT channel, COUNT(*) AS orders, SUM(amount) AS revenue FROM orders GROUP BY channel ORDER BY channel');
  await page.getByRole('button', { name: '执行查询', exact: true }).click();
  await page.getByRole('cell', { name: 'web', exact: true }).first().waitFor();
  await screenshot('desktop-query.png');
  await page.getByRole('button', { name: '生成报表', exact: true }).click();
  await page.getByLabel('报表标题').fill('桌面验证 · 渠道订单');
  await page.getByRole('dialog').getByRole('button', { name: '生成报表', exact: true }).click();
  await page.getByRole('button', { name: /桌面验证 · 渠道订单/ }).click();
  await page.getByRole('heading', { name: '桌面验证 · 渠道订单' }).waitFor();
  const metric = page.getByLabel('图表数值指标');
  assert.equal(await metric.inputValue(), '1', 'report defaults to one numeric metric');
  await metric.selectOption('2');
  assert.equal(await metric.inputValue(), '2', 'report metric can switch to revenue');
  await page.getByText('示例数据库查询', { exact: true }).waitFor();
  await page.waitForTimeout(400);
  await screenshot('desktop-report.png');
  await navigation.getByRole('button', { name: '模型配置', exact: true }).click();
  await page.getByRole('heading', { name: '模型配置', exact: true }).waitFor();
  await screenshot('desktop-settings.png');
  await page.getByRole('button', { name: '添加模型', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await screenshot('desktop-model-dialog.png');
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click();
  await navigation.getByRole('button', { name: 'AI 问答', exact: true }).click();
  const input = page.locator('#bm-chat-input');
  await input.fill('退款规则是什么？');
  await navigation.getByRole('button', { name: '项目与仓库', exact: true }).click();
  await page.getByRole('heading', { name: '项目与仓库', exact: true }).waitFor();
  await navigation.getByRole('button', { name: 'AI 问答', exact: true }).click();
  assert.equal(await input.inputValue(), '退款规则是什么？', 'navigation preserves the conversation draft');
  await page.getByRole('button', { name: '发送问题', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.bm-chat-message').length === 2 && !document.querySelector('.bm-chat-waiting'));
  const firstChat = (await api('GET', '/api/chats')).chats.find(chat => chat.title.includes('退款规则是什么'));
  assert.ok(firstChat, 'submitted conversation appears in persisted history');
  const persisted = await api('GET', `/api/chats/${firstChat.id}`);
  assert.equal(persisted.messages.length, 2);
  assert.ok(persisted.messages[1].sources.length > 0, 'conversation answer cites real knowledge');
  await input.fill('留在第一段会话的草稿');
  await page.getByRole('button', { name: '新建对话', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#bm-chat-input')?.value === '');
  const history = page.getByRole('navigation', { name: '选择对话' });
  await history.getByRole('button', { name: /退款规则是什么/ }).click();
  assert.equal(await input.inputValue(), '留在第一段会话的草稿', 'switching conversations preserves drafts independently');
  await screenshot('desktop-chat-answer-dark.png');
  await page.reload();
  await page.getByRole('navigation', { name: '选择对话' }).getByRole('button', { name: /退款规则是什么/ }).click();
  await page.waitForFunction(() => document.querySelectorAll('.bm-chat-message').length === 2);
  assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'dark', 'theme persists across reload');
  await page.getByRole('button', { name: '新建对话', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.bm-chat-message').length === 0);
  await screenshot('desktop-chat-dark.png');
  await page.getByRole('button', { name: '浅色主题', exact: true }).click();
  await screenshot('desktop-chat-light.png');
  assert.deepEqual(errors, [], 'no renderer exceptions');
  const reportData = { platform: process.platform, packaged: !!packaged, version: await desktop.evaluate(({ app }) => app.getVersion()), tested_at: new Date().toISOString(), notes: notes.length, links: graph.edges.length, query_rows: result.row_count, tests: ['desktop boot', 'Markdown read/write', 'optimistic conflict', 'real graph', 'read-only query', 'denied write unchanged data', 'result-bound report', 'grounded support', 'ordered five-section navigation', 'light/dark theme and persistence', 'graph and knowledge UI', 'SQL UI execution', 'report UI creation and metric selection', 'model and MCP settings UI', 'persisted conversations and source citations', 'draft retention across navigation and conversations', 'conversation history after reload'], renderer_errors: errors, capture_method: 'electron-native' };
  await writeFile(resolve(artifacts, packaged ? 'packaged-smoke.json' : 'desktop-smoke.json'), JSON.stringify(reportData, null, 2));
  console.log(JSON.stringify(reportData, null, 2));
} finally {
  await desktop.close();
}
