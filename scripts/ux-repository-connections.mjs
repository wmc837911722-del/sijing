  child.on('close', () => {
    const data = Buffer.concat(chunks), separator = data.indexOf('\r\n\r\n');
    if (separator < 0) { res.writeHead(500); res.end(); return; }
    const headers = {}; let status = 200;
    for (const line of data.subarray(0, separator).toString().split('\r\n')) {
      const index = line.indexOf(':'); if (index < 0) continue;
      const name = line.slice(0, index), value = line.slice(index + 1).trim();
      if (name.toLowerCase() === 'status') status = Number(value.slice(0, 3)); else headers[name] = value;
    }
    res.writeHead(status, headers); res.end(data.subarray(separator + 4));
  });
  req.pipe(child.stdin);
