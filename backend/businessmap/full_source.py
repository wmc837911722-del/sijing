"""Complete, bounded local Git source inventory for project analysis.

The index's 128 KB/file and 500-file limits never define this inventory.
Exclusions are explicit. Only sanitized text is retained in the blob cache.
"""
from __future__ import annotations

import re
import subprocess
import sys
import threading
import weakref
from collections import OrderedDict
from pathlib import Path, PurePosixPath

from .core import CoreError, Store
from .source_evidence import SourceNavigator


_SECRET_KEY = r"[\w.-]*(?:password|passwd|secret|api[_-]?key|app[_-]?key|access[_-]?key|private[_-]?key|token)[\w.-]*"
_QUOTED_SECRET = re.compile(
    r"(?i)(?<![\w])([\"']?" + _SECRET_KEY + r"[\"']?\s*[:=]\s*)"
    r"([\"'`])(?:\\[^\r\n]|(?!\2)[^\\\r\n])*?\2")
_MULTILINE_SECRET = re.compile(
    r"(?is)(?<![\w])([\"']?" + _SECRET_KEY + r"[\"']?\s*[:=]\s*)(\"\"\"|'''|`)(.*?)\2")
_XML_SECRET = re.compile(r"(?is)(<(?:password|passwd|secret|api[_-]?key|access[_-]?key|token)\b[^>]*>)(.*?)(</[^>]+>)")
_PLAIN_CONFIG_SECRET = re.compile(
    r"(?im)^(\s*[\"']?" + _SECRET_KEY + r"[\"']?\s*[:=]\s*)([^\s#\"'`][^\r\n#]*)")
_PRIVATE_KEY = re.compile(r"-----BEGIN [^-\r\n]*PRIVATE KEY-----.*?-----END [^-\r\n]*PRIVATE KEY-----", re.S)
_KNOWN_TOKEN = re.compile(r"\b(?:sk-[A-Za-z0-9_-]{20,}|gh[pousr]_[A-Za-z0-9]{20,}|AKIA[A-Z0-9]{16})\b")
_CREDENTIAL_URL = re.compile(r"(?i)(?<![a-z0-9+.-])([a-z][a-z0-9+.-]*://)[^\s/@:'\"<>]+:[^\s/@'\"<>]+@")
_BEARER = re.compile(r"(?i)(\bBearer\s+)[A-Za-z0-9_.~+/-]{12,}=*")

# Metadata only. Weak Store keys prevent this cache from owning a workspace
# lifetime; cached rows are immutable and never contain source/blob text.
_METADATA_CACHES = weakref.WeakKeyDictionary()
_METADATA_LOCK = threading.RLock()


def _metadata_size(value):
    seen = set()
    def measure(item):
        if id(item) in seen:
            return 0
        seen.add(id(item))
        return sys.getsizeof(item) + (sum(measure(child) for child in item) if isinstance(item, tuple) else 0)
    return measure(value)


def redact_source(content, path=""):
    """Remove literal credentials while keeping every LF and source line number."""
    hide_lines = lambda value: re.sub(r"[^\r\n]+", "[REDACTED]", value)
    result = _MULTILINE_SECRET.sub(lambda m: m[1] + m[2] + hide_lines(m[3]) + m[2], content)
    result = _QUOTED_SECRET.sub(lambda m: m[1] + '"[REDACTED]"', result)
    result = _XML_SECRET.sub(lambda m: m[1] + hide_lines(m[2]) + m[3], result)
    if PurePosixPath(path).suffix.casefold() in {".yaml", ".yml", ".properties", ".toml"}:
        result = _PLAIN_CONFIG_SECRET.sub(lambda m: m[1] + "[REDACTED]" + ("\r" if m[2].endswith("\r") else ""), result)
    result = _PRIVATE_KEY.sub(lambda m: hide_lines(m[0]), result)
    result = _KNOWN_TOKEN.sub("[REDACTED]", result)
    if "://" in result:
        result = _CREDENTIAL_URL.sub(r"\1[REDACTED]@", result)
    result = _BEARER.sub(r"\1[REDACTED]", result)
    return result, result != content


class FullSourceInventory:
    POLICY_VERSION = "full-source-v4-password-business-sources"
    MAX_FILE_BYTES = 8 * 1024 * 1024
    MAX_CACHE_BYTES = 64 * 1024 * 1024
    METADATA_CACHE_ENTRIES = 8
    METADATA_CACHE_BYTES = 32 * 1024 * 1024
    EXTRA_SOURCE_SUFFIXES = {
        ".mjs", ".cjs", ".mts", ".cts", ".swift", ".dart", ".c", ".h", ".cpp", ".hpp",
        ".scala", ".groovy", ".svelte", ".html", ".css", ".scss", ".sass", ".less", ".wxml", ".wxss",
    }
    CONTRACT_SUFFIXES = {".json", ".xml", ".yaml", ".yml", ".kts", ".gradle", ".properties", ".toml"}
    GENERATED_PARTS = {"generated", "__generated__", "autogenerated", "coverage", "__pycache__"}
    LOCK_NAMES = {"package-lock.json", "npm-shrinkwrap.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock", "bun.lockb", "composer.lock", "poetry.lock", "uv.lock", "gradle.lockfile"}
    JSON_NAMES = {"package.json", "pages.json", "manifest.json"}

    def __init__(self, store, repository):
        repository_id = repository["id"] if isinstance(repository, dict) else repository
        self._navigator = SourceNavigator(store, repository_id, load_inventory=False)
        self.store = store
        self.repo = dict(self._navigator.repo)
        self.repository_id, self.commit = self._navigator.repository_id, self._navigator.commit
        if isinstance(repository, dict) and any(repository.get(k) != self.repo.get(k) for k in
                                               ("commit", "path", "vault_path") if k in repository):
            raise CoreError(409, "完整分析的仓库快照已变化")
        self.excluded = []
        self.file_map = {}
        self._cache, self._cache_bytes = OrderedDict(), 0
        self._batch, self._closed = None, False
        self._lock = threading.RLock()
        files, excluded = self._metadata()
        self.file_map = {path: {"path": path, "blob": blob, "size": size, "kind": kind,
                                "repository_id": self.repository_id, "commit": self.commit}
                         for path, blob, size, kind in files}
        self.files = [dict(item) for item in self.file_map.values()]
        self.excluded = [{"path": path, "reason": reason, "size": size} for path, reason, size in excluded]
        self._navigator._guard()

    def _metadata(self):
        key = (self.repository_id, self.repo["path"], self.commit, self.repo.get("vault_path"),
               self._navigator.vault, self._navigator.epoch, self.POLICY_VERSION, self.MAX_FILE_BYTES)
        # Singleflight prevents every analysis worker from rebuilding the same
        # repository's thousands of path-safety decisions under the GIL.
        with _METADATA_LOCK:
            cache = _METADATA_CACHES.setdefault(self.store, {"entries": OrderedDict(), "bytes": 0})
            entries = cache["entries"]
            while entries and (len(entries) > self.METADATA_CACHE_ENTRIES or cache["bytes"] > self.METADATA_CACHE_BYTES):
                _, (_, weight) = entries.popitem(last=False)
                cache["bytes"] -= weight
            if key in entries:
                entries.move_to_end(key)
                return entries[key][0]
            result = self._scan_metadata()
            weight = _metadata_size((key, result)) + 1024  # LRU/container overhead.
            if self.METADATA_CACHE_ENTRIES > 0 and weight <= self.METADATA_CACHE_BYTES:
                while entries and (len(entries) >= self.METADATA_CACHE_ENTRIES
                                   or cache["bytes"] + weight > self.METADATA_CACHE_BYTES):
                    _, (_, old_weight) = entries.popitem(last=False)
                    cache["bytes"] -= old_weight
                entries[key] = result, weight
                cache["bytes"] += weight
            return result

    def _scan_metadata(self):
        files, excluded = [], []
        raw = self._navigator._run_git(["ls-tree", "-r", "-l", "-z", self.commit],
                                       max_bytes=SourceNavigator.MAX_METADATA_BYTES)
        for entry in raw.split(b"\0"):
            if not entry or b"\t" not in entry:
                continue
            metadata, raw_path = entry.split(b"\t", 1)
            fields = metadata.split()
            if len(fields) != 4:
                raise CoreError(502, "Git 返回了无效的文件清单")
            mode, kind, blob, size = fields
            path = raw_path.decode("utf-8", "replace")
            size = int(size) if size.isdigit() else None
            if mode not in {b"100644", b"100755"} or kind != b"blob":
                reason = "non_regular"
            elif b"\xef\xbf\xbd" in path.encode("utf-8") and raw_path != path.encode("utf-8"):
                reason = "invalid_path_encoding"
            else:
                reason = self._excluded_reason(path, size)
            if reason:
                excluded.append((path, reason, size))
                continue
            blob = blob.decode("ascii")
            if not re.fullmatch(r"[a-f0-9]{40,64}", blob):
                raise CoreError(502, "Git 返回了无效的文件版本")
            files.append((path, blob, size, self._kind(path)))
        return tuple(sorted(files)), tuple(sorted(excluded))

    @classmethod
    def _contract(cls, path):
        pure = PurePosixPath(path)
        name = pure.name.casefold()
        if pure.suffix.casefold() == ".json":
            return name in cls.JSON_NAMES or any(word in name for word in ("openapi", "swagger", "schema", "route", "permission"))
        if pure.suffix.casefold() in {".yaml", ".yml"}:
            return any(word in name for word in ("openapi", "swagger", "schema", "route"))
        if pure.suffix.casefold() == ".xml":
            return (name in {"pom.xml", "androidmanifest.xml", "web.xml"}
                    or any(word in name for word in ("mapper", "schema", "route"))
                    or any(part.casefold() in {"mapper", "mappers", "layout", "navigation"} for part in pure.parts))
        return name in {"build.gradle", "settings.gradle", "build.gradle.kts", "settings.gradle.kts", "libs.versions.toml"}

    @classmethod
    def _excluded_reason(cls, path, size):
        if not SourceNavigator._valid_path(path):
            return "invalid_path"
        pure = PurePosixPath(path)
        parts, name, suffix = pure.parts, pure.name.casefold(), pure.suffix.casefold()
        # Apply the existing source filter to a neutral extension as well, so
        # supplementary contracts inherit hidden/vendor/credential safeguards.
        typed_business = (suffix in {".java", ".kt", ".cs"}
                          and re.fullmatch(r"[A-Z][A-Za-z0-9_]*", pure.stem)
                          and re.search(r"(?:^|/)src/(?:main|test)/(?:java|kotlin|csharp)/", path))
        password_business = ("password" in pure.stem.casefold()
                             and not any(word in pure.stem.casefold() for word in
                                         ("credential", "secret", "private-key", "private_key"))
                             and (suffix == ".vue" and "src" in parts
                                  and any(part in {"components", "views", "pages"} for part in parts)
                                  or suffix in Store.SOURCE_SUFFIXES | cls.EXTRA_SOURCE_SUFFIXES
                                  and cls._kind(path) == "test"
                                  or suffix == ".sql" and "password_version" in name
                                  and re.match(r"V\d[\w.]*__", pure.name)
                                  and any(part in {"db", "migrations"} for part in parts)))
        # AgentCredential/ChangePasswordRequest are business code, not key
        # material. Retain all directory guards while allowing typed classes
        # under standard source roots; literal credentials are still scrubbed.
        neutral = str(pure.with_name("Source.py") if typed_business or password_business else pure.with_suffix(".py"))
        if not Store._safe_source(neutral, 0):
            return "unsafe_path"
        if any(part.casefold() in cls.GENERATED_PARTS for part in parts) or re.search(r"\.(?:min|generated)\.", name):
            return "generated"
        if name in cls.LOCK_NAMES:
            return "dependency_lock"
        if (name in {"gradle.properties", "local.properties", "project.private.config.json", "project.config.json"}
                or re.match(r"(?:application|bootstrap|appsettings)(?:[-.].*)?\.(?:json|ya?ml|properties)$", name)
                or suffix in {".properties", ".env"}):
            return "environment_config"
        if not (typed_business or password_business or Store._safe_source(path, 0)
                or suffix in cls.EXTRA_SOURCE_SUFFIXES or cls._contract(path)):
            return "outside_source_scope"
        if size is None or size > cls.MAX_FILE_BYTES:
            return "resource_limit"
        return None

    @classmethod
    def _kind(cls, path):
        pure = PurePosixPath(path)
        if (any(part.casefold() in {"test", "tests", "__tests__", "androidtest", "screenshottest",
                                   "debug", "fixtures", "fixture", "samples"} for part in pure.parts)
                or re.search(r"(?:^test_|[._](?:test|spec)[._]|(?:Test|Tests)\.[^.]+$)", pure.name)):
            return "test"
        return "contract" if pure.suffix.casefold() in cls.CONTRACT_SUFFIXES else "source"

    def _start_batch(self):
        command, env = self._navigator._git_invocation(["cat-file", "--batch"])
        try:
            self._batch = subprocess.Popen(command, cwd=Path(self.repo["path"]), env=env, shell=False,
                                           stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        except OSError:
            raise CoreError(502, "无法启动只读 Git 完整源码读取") from None

    def _stop_batch(self):
        process, self._batch = self._batch, None
        if process is None:
            return
        if process.poll() is None:
            process.kill()
        process.wait(timeout=2)
        process.stdin.close()
        process.stdout.close()

    def _read_blob(self, item):
        # Config formats allow unquoted literals. A .py alias must not weaken
        # the redaction applied to identical bytes used as a YAML contract.
        config_literal = PurePosixPath(item["path"]).suffix.casefold() in {".yaml", ".yml", ".properties", ".toml"}
        cache_key = item["blob"], config_literal
        if cache_key in self._cache:
            self._cache.move_to_end(cache_key)
            return self._cache[cache_key]
        if self._batch is None or self._batch.poll() is not None:
            self._stop_batch()
            self._start_batch()
        process = self._batch
        timed_out = threading.Event()
        def expire():
            timed_out.set()
            try:
                process.kill()
            except OSError:
                pass
        timer = threading.Timer(self._navigator.COMMAND_TIMEOUT, expire)
        timer.daemon = True
        timer.start()
        try:
            process.stdin.write((item["blob"] + "\n").encode("ascii"))
            process.stdin.flush()
            header = process.stdout.readline(256).split()
            if header != [item["blob"].encode(), b"blob", str(item["size"]).encode()]:
                raise CoreError(502, "完整源码对象与清单不一致")
            raw = process.stdout.read(item["size"])
            if len(raw) != item["size"] or process.stdout.read(1) != b"\n":
                raise CoreError(502, "完整源码读取未完成")
            try:
                content = raw.decode("utf-8-sig")
            except UnicodeError:
                raise CoreError(415, "源码必须是 UTF-8 文本") from None
            if b"\0" in raw:
                # A checked-in Kotlin logger uses a literal NUL inside a char
                # literal. It is readable UTF-8 source, not a binary payload.
                # Accept only this exact spelling in standard typed roots;
                # every other NUL-bearing object retains the binary rejection.
                typed_root = (PurePosixPath(item["path"]).suffix.casefold() in {".java", ".kt"}
                              and re.search(r"(?:^|/)src/(?:main|debug|test)/(?:java|kotlin)/", item["path"]))
                if not typed_root or raw.count(b"\0") != raw.count(b"'\0'"):
                    raise CoreError(415, "二进制文件不能作为源码证据")
            # Keep only sanitized text. Never persist the raw literal secrets.
            result = redact_source(content, item["path"])
        except (OSError, CoreError):
            self._stop_batch()
            if timed_out.is_set():
                raise CoreError(408, "完整源码只读操作超时") from None
            raise
        finally:
            timer.cancel()
        if timed_out.is_set():
            self._stop_batch()
            raise CoreError(408, "完整源码只读操作超时")
        weight = len(result[0].encode("utf-8"))
        while self._cache and self._cache_bytes + weight > self.MAX_CACHE_BYTES:
            _, old = self._cache.popitem(last=False)
            self._cache_bytes -= len(old[0].encode("utf-8"))
        if weight <= self.MAX_CACHE_BYTES:
            self._cache[cache_key] = result
            self._cache_bytes += weight
        return result

    def read(self, item):
        with self._lock:
            if self._closed:
                raise CoreError(409, "完整源码读取会话已关闭")
            self._navigator._guard()
            path = item.get("path") if isinstance(item, dict) else item
            if not SourceNavigator._valid_path(path):
                raise CoreError(400, "源码路径必须是仓库内的相对路径")
            canonical = self.file_map.get(path)
            if canonical is None:
                raise CoreError(404, "源码不在完整分析的安全跟踪文件范围内")
            if isinstance(item, dict) and any(item[k] != canonical[k] for k in
                                            ("blob", "size", "repository_id", "commit") if k in item):
                raise CoreError(409, "源码对象与固定仓库快照不一致")
            content, redacted = self._read_blob(canonical)
            self._navigator._guard()
            return {**canonical, "content": content, "redacted": redacted,
                    "original_bytes": canonical["size"], "content_bytes": len(content.encode("utf-8")),
                    "total_lines": len(SourceNavigator._lines(content)), "untrusted": True}

    def close(self):
        with self._lock:
            self._stop_batch()
            self._cache.clear()
            self._cache_bytes = 0
            self._closed = True

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self.close()
